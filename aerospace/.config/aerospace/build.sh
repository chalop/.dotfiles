#!/bin/bash
# aerospace reads a single file and has no include, so the shareable config
# (aerospace.base.toml) and the private per machine rules (aerospace.local.toml,
# untracked, optional) are joined into aerospace.toml, also untracked.
# run it after editing either file.

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

{
    echo "# generated by build.sh from aerospace.base.toml and aerospace.local.toml, do not edit"
    cat aerospace.base.toml
    [[ -f aerospace.local.toml ]] && { echo; cat aerospace.local.toml; }
} > aerospace.toml

aerospace reload-config 2> /dev/null || echo "generated aerospace.toml, aerospace is not running so it was not reloaded"
